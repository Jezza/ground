impl<'a> VisitMut<'a> for ApiBuilder {
    fn visit_paths_mut(&mut self, node: &'a mut Paths) {
        visit_mut::visit_paths_mut(self, node);

        let mut map = indexmap::IndexMap::new();
        std::mem::swap(&mut map, &mut node.paths);

        // Each path item contains the name of the originating api it came from.
        // We do this, so we can differentiate differing routes and operation ids.
        // API routes that come from the same api will collide.
        // Eg, ops and partner apis will both have operations that use the same operation id.
        let Some(Value::String(name)) = node.extensions.get(GROUND_NAME) else {
            panic!("Paths have no tags")
        };
        let name = name.clone();

        for (path, mut item) in map.into_iter() {
            // if !self.opts.include_hidden_routes && path.starts_with("/inc/") {
            //     continue;
            // }

            let path = format!("/{}__{}", name, path);

            if let ReferenceOr::Item(item) = &mut item {
                utils::visit_op_mut(item, |_, op| {
                    if let Some(id) = op.operation_id.as_mut() {
                        id.insert_str(0, &format!("{}__", name));
                    }
                });
            }

            if let Some(previous) = node.paths.insert(path.clone(), item) {
                panic!("URL collision: {}: {:#?}", path, previous);
            }
        }
    }

    fn visit_operation_mut(&mut self, node: &'a mut Operation) {
        // Recursively replace all the schemas, etc, before we start working on it.
        visit_mut::visit_operation_mut(self, node);

        let Some(req_body) = node.request_body.as_mut() else {
            return;
        };

        let operation_id = node
            .operation_id
            .as_deref()
            .expect("Operations should have operation ids");
        let operation_id = case::convert(operation_id, case::Case::Pascal);

        let tag = node
            .tags
            .first()
            .map(|item| format!("{}.", item))
            .unwrap_or_default();

        let full_name = format!("{}{}Request", tag, operation_id);
        let full_reference = format!("#/components/requestBodies/{}", full_name);

        let mut reference = ReferenceOr::Reference {
            reference: full_reference,
        };
        std::mem::swap(req_body, &mut reference);

        let components = self.openapi.components.as_mut().expect("Should be set");
        components.request_bodies.insert(full_name, reference);
    }
}
