use crate::{GROUND_EXTERNAL, GROUND_EXTERNAL_TYPES, GROUND_NAME, GROUND_TAGS};

pub fn build(opts: BuilderOpts, paths: Vec<Paths>) -> anyhow::Result<OpenAPI> {
    let mut builder = ApiBuilder::new(opts);

    for mut paths in paths {
        // Copy the tags over
        if let Some(tags) = paths.extensions.swap_remove(GROUND_TAGS) {
            let tags: Vec<openapiv3::Tag> = serde_json::from_value(tags).expect("Tags are invalid");
            builder.openapi.tags.extend(tags);
        }

        if let Some(types) = paths.extensions.swap_remove(GROUND_EXTERNAL_TYPES) {
            let types: indexmap::IndexMap<String, Schema> =
                serde_json::from_value(types).expect("External types are invalid");

            for (_, ty) in types {
                let Some(Value::String(name)) = ty.schema_data.extensions.get(GROUND_NAME) else {
                    panic!("Unnamed external.");
                };
                let name = name.clone();
                let Some(Value::Bool(true)) = ty.schema_data.extensions.get(GROUND_EXTERNAL) else {
                    panic!("External wasn't marked as such: {}", name);
                };

                builder.visit_reference_or_schema_mut(&mut ReferenceOr::Item(ty));
            }
        }

        builder.visit_paths_mut(&mut paths);
        builder.openapi.paths.paths.extend(paths.paths);
    }

    builder
        .openapi
        .tags
        .sort_by(|left, right| left.name.cmp(&right.name));
    builder
        .openapi
        .tags
        .dedup_by(|left, right| left.name == right.name);

    if let Some(components) = builder.openapi.components.as_mut() {
        components.schemas.sort_keys();
    }

    Ok(builder.openapi)
}

#[derive(Debug, Clone)]
pub struct BuilderOpts {
    // This marks externals used within the input explicitly as "external".
    // This lets you easily distinguish internal vs external types visually.
    // (ie, you'd see `ground_api::external::ApiError` vs `crate::models::ApiError`)
    // `external` _doesn't_ mean things like "Uuid" (those are "known" types)
    //
    // Implementation-wise, disabling this strips the "external:" part of the reference that we use to identify externals.
    // We use the external prefix to specifically mark the path in the generated code.
    // pub explicit_externals: bool,
}

impl Default for BuilderOpts {
    fn default() -> Self {
        Self {
            // explicit_externals: false,
        }
    }
}

